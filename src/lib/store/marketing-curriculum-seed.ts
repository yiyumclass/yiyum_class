type SeedItem = {
  key: string;
  title: string;
  lessonNumber: number | null;
  kind: "lesson" | "assignment";
};

function lesson(lessonNumber: number, title: string): SeedItem {
  return { key: `lesson-${lessonNumber}`, title, lessonNumber, kind: "lesson" };
}

function assignment(date: string, title: string, lessonNumber: number | null = null): SeedItem {
  return { key: `assignment-${date}`, title, lessonNumber, kind: "assignment" };
}

