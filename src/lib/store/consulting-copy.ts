/**
 * 컨설팅 상세 원고.
 *
 * 관리자 편집 대상이 아니다. 판매 문구는 한 번 확정되면 자주 바뀌지 않는 반면,
 * 문구마다 편집 화면을 붙이면 유형이 늘 때마다 그 화면을 또 만들어야 한다.
 * 대신 구조는 데이터로 두어, 나중에 편집이 필요해지면 이 모양 그대로 테이블로
 * 옮기고 렌더러는 손대지 않는다.
 *
 * 가격, 정가, 품절, 썸네일은 여기 두지 않는다. 그 값들은 상품 DB가 가지고
 * 있어야 운영자가 직접 바꿀 수 있다.
 */
